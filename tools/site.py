#!/usr/bin/env python3
"""Generates the download page in every language from one template.

    python3 tools/site.py           write index.html, <lang>/index.html, sitemap.xml
    python3 tools/site.py --check   fail if any of them is not what it would write
    python3 tools/site.py --langs   print the language codes, root language first

The template is src/site/page.html and the words are src/site/<lang>.json. The
first language in LANGS is served at the site root and the others in a folder
of their own, so each language has an address a search engine can index. Every
language file must have exactly the keys the English one has: a missing string
is an error here rather than a blank on the page.
"""

import html
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SITE = ROOT / 'src' / 'site'
BASE = 'https://fcardinaux.github.io/study-templates/'

# Code, name in its own language, Open Graph locale. The first is the root page.
LANGS = [
    ('en', 'English', 'en_GB'),
    ('fr', 'Français', 'fr_FR'),
    ('de', 'Deutsch', 'de_DE'),
    ('it', 'Italiano', 'it_IT'),
    ('es', 'Español', 'es_ES'),
]

TITLE_MAX, DESCRIPTION_MAX = 60, 155

GENERATED = ('Generated by tools/site.py from src/site/page.html and '
             'src/site/<lang>.json. Edit those, then run ./build.sh.')


def load():
    strings = {code: json.loads((SITE / f'{code}.json').read_text())
               for code, _, _ in LANGS}
    ref = strings['en']
    for code, data in strings.items():
        for section, values in ref.items():
            have = data.get(section, {})
            missing = [k for k in values if k not in have]
            extra = [k for k in have if k not in values]
            if missing or extra:
                sys.exit(f'{code}.json, "{section}": missing {missing}, unexpected {extra}')
        if set(data) != set(ref):
            sys.exit(f'{code}.json: sections {sorted(data)}, expected {sorted(ref)}')
        # Search results cut a title at about 60 characters and a description at
        # about 155, and every translation runs longer than the English, so the
        # limits are enforced rather than remembered.
        for key, limit in (('title', TITLE_MAX), ('description', DESCRIPTION_MAX)):
            n = len(data['html'][key])
            if n > limit:
                sys.exit(f'{code}.json: "{key}" is {n} characters, over {limit}; '
                         'search results would cut it')
        # Keep English's order, which is the order things appear on the page.
        strings[code] = {s: {k: data[s][k] for k in ref[s]} for s in ref}
    return strings


def url(code):
    return BASE if code == LANGS[0][0] else f'{BASE}{code}/'


def page(template, code, locale, strings):
    s = strings[code]
    # './' rather than '': a module import must start with a dot or a slash, and
    # the page imports src/layouts.js through this prefix.
    root = './' if code == LANGS[0][0] else '../'
    here = url(code)

    def href(other):
        rel = '' if other == LANGS[0][0] else f'{other}/'
        return root + rel

    langs = [{'code': c, 'name': n, 'href': href(c),
              'offer': strings[c]['js']['offer'], 'close': strings[c]['js']['close']}
             for c, n, _ in LANGS]
    alternates = '\n'.join(
        [f'<link rel="alternate" hreflang="{c}" href="{url(c)}">' for c, _, _ in LANGS]
        + [f'<link rel="alternate" hreflang="x-default" href="{BASE}">'])
    switch = ' '.join(
        f'<a href="{l["href"]}" data-base="{l["href"]}" hreflang="{l["code"]}" lang="{l["code"]}"'
        + (' aria-current="page"' if l['code'] == code else '') + f'>{l["name"]}</a>'
        for l in langs)
    social = f'{BASE}previews/social{"" if code == LANGS[0][0] else "-" + code}.png'
    jsonld = json.dumps({
        '@context': 'https://schema.org',
        '@type': 'CreativeWork',
        'name': s['html']['og_title'],
        'description': s['html']['jsonld_description'],
        'url': here,
        'image': social,
        'author': {'@type': 'Person', 'name': 'François Cardinaux',
                   'url': 'https://github.com/fcardinaux'},
        'license': 'https://creativecommons.org/licenses/by/4.0/',
        'isAccessibleForFree': True,
        'encodingFormat': 'application/pdf',
        'inLanguage': code,
    }, ensure_ascii=False, indent=2)
    runtime = {'lang': code, 'root': root, 'langs': langs,
               **{k: s[k] for k in ('js', 'views', 'sizes', 'kinds', 'titles')}}
    # A JSON string cannot contain "</", so nothing in it can close the script.
    as_script = lambda v: json.dumps(v, ensure_ascii=False).replace('</', '<\\/')

    fixed = {
        'generated': GENERATED, 'lang': code, 'locale': locale, 'root': root,
        'url': here, 'alternates': alternates, 'langswitch': switch,
        'social': social, 'jsonld': jsonld.replace('</', '<\\/'),
        'strings': as_script(runtime),
    }

    def sub(m):
        key, attr = m.group(1), m.group(2)
        if key in fixed:
            value = fixed[key]
        else:
            section, _, name = key.partition('.')
            try:
                value = s[section][name]
            except KeyError:
                sys.exit(f'page.html uses {{{{{key}}}}}, which {code}.json does not have')
        return html.escape(value, quote=True) if attr else value

    out = re.sub(r'\{\{([\w.-]+)(\|attr)?\}\}', sub, template)
    left = re.findall(r'\{\{[^}]*\}\}', out)
    if left:
        sys.exit(f'{code}: unfilled placeholders {left}')
    return out


def sitemap():
    xhtml = '\n'.join(f'    <xhtml:link rel="alternate" hreflang="{c}" href="{url(c)}"/>'
                      for c, _, _ in LANGS)
    entries = '\n'.join(f'  <url>\n    <loc>{url(c)}</loc>\n{xhtml}\n  </url>'
                        for c, _, _ in LANGS)
    return ('<?xml version="1.0" encoding="UTF-8"?>\n'
            '<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9"\n'
            '        xmlns:xhtml="http://www.w3.org/1999/xhtml">\n'
            f'{entries}\n</urlset>\n')


def main():
    if '--langs' in sys.argv[1:]:
        print(' '.join(code for code, _, _ in LANGS))
        return
    check = '--check' in sys.argv[1:]
    template = (SITE / 'page.html').read_text()
    strings = load()
    outputs = {ROOT / 'sitemap.xml': sitemap()}
    for code, _, locale in LANGS:
        path = ROOT / 'index.html' if code == LANGS[0][0] else ROOT / code / 'index.html'
        outputs[path] = page(template, code, locale, strings)

    stale = []
    for path, text in outputs.items():
        if check:
            if not path.exists() or path.read_text() != text:
                stale.append(str(path.relative_to(ROOT)))
        else:
            path.parent.mkdir(exist_ok=True)
            path.write_text(text)
    if stale:
        sys.exit(f'out of date, run ./build.sh: {", ".join(stale)}')


if __name__ == '__main__':
    main()
